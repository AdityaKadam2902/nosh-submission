"""Regenerate docs/INTERFACES.md (public signatures of every module) so fresh chats see the REAL contracts.  python -m scripts.gen_interfaces"""
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def sig(fn) -> str:
    a = ast.unparse(fn.args)
    r = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"{'async ' if isinstance(fn, ast.AsyncFunctionDef) else ''}def {fn.name}({a}){r}"


def first_line(node) -> str:
    d = ast.get_docstring(node)
    return d.strip().splitlines()[0] if d else ""


def main() -> int:
    out = ["# INTERFACES (auto-generated by scripts/gen_interfaces.py; public names only)", ""]
    for folder in ("recipebot", "scripts"):
        for p in sorted((ROOT / folder).glob("*.py")):
            if p.name == "__init__.py":
                continue
            tree = ast.parse(p.read_text(encoding="utf-8"))
            out += [f"## {folder}/{p.name}", first_line(tree) and f"_{first_line(tree)}_", ""]
            for n in tree.body:
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_"):
                    out.append(f"- `{sig(n)}`" + (f" — {first_line(n)}" if first_line(n) else ""))
                elif isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
                    out.append(f"- `class {n.name}`" + (f" — {first_line(n)}" if first_line(n) else ""))
                    for m in n.body:
                        if isinstance(m, ast.FunctionDef) and not m.name.startswith("_"):
                            out.append(f"    - `{sig(m)}`")
            out.append("")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "INTERFACES.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote docs/INTERFACES.md ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
